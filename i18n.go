package main

import (
	"fmt"
	"sync/atomic"
)

var uiLanguage atomic.Value

func setUILanguage(tag string) {
	if len(tag) >= 2 && (tag[:2] == "en") {
		uiLanguage.Store("en")
		return
	}
	uiLanguage.Store("zh")
}

func currentUILanguage() string {
	if v, ok := uiLanguage.Load().(string); ok && v == "en" {
		return "en"
	}
	return "zh"
}

// tr says a UI message in the app language; untranslated text stays as written.
func tr(s string) string {
	if currentUILanguage() != "en" {
		return s
	}
	if v, ok := englishText[s]; ok {
		return v
	}
	return s
}

// trf translates a format string before its arguments are filled in, so a
// message with numbers or names can be translated as a whole.
func trf(format string, args ...any) string {
	if len(args) == 0 {
		return tr(format)
	}
	return fmt.Sprintf(tr(format), args...)
}

